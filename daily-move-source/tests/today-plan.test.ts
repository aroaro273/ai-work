import assert from 'node:assert/strict';
import {freshState,readState,writeProfile,writeRecord,writeState} from '../lib/local-store';
import {dayIndex,type Exercise,type RecordDay} from '../lib/model';
import {reconcileToday} from '../lib/today-plan';
const storage=new Map<string,string>();
Object.assign(globalThis,{localStorage:{getItem:(k:string)=>storage.get(k)??null,setItem:(k:string,v:string)=>storage.set(k,v)}});
const today='2026-11-22';
assert.equal(dayIndex(today),6);
const make=(id:string):Exercise=>({id,kind:'걷기',name:id,minutes:10,reps:0,sets:0});
const a=make('a'),b=make('b'),c=make('c');
const record=(date=today):RecordDay=>({date,items:[a,b],done:['a'],rest:false,finished:false});
const original=freshState();original.plan[6]={rest:false,items:[a,b]};original.records=[record(),record('2026-11-21')];writeState(original);
const plan=structuredClone(original.plan);plan[6].items=[{...a,name:'changed',minutes:30},c];
const updated=writeProfile(plan,original.settings,today);
assert.deepEqual(updated.records[0].items,[a,c]);
assert.deepEqual(updated.records[0].done,['a']);
assert.deepEqual(updated.records[1],original.records[1]);
assert.deepEqual(readState(),updated);
assert.deepEqual(readState().plan[6].items,plan[6].items);
assert.deepEqual(reconcileToday(record(),{rest:false,items:[c]}).items,[c,a]);
const resting={...record(),items:[],done:[],rest:true,finished:true};
assert.deepEqual(reconcileToday(resting,{rest:false,items:[c]}),{...resting,items:[c],rest:false,finished:false});
const finished={...record(),done:['a','b'],finished:true};
assert.equal(reconcileToday(finished,{rest:false,items:[a,b,c]}).finished,false);
const partial={...record(),finished:true};
assert.equal(reconcileToday(partial,{rest:false,items:[a,b]}).finished,true);
writeRecord({...record(),items:[a,c]});
assert.deepEqual(readState().records.find(r=>r.date===today)?.items,[a,c]);
const fresh=freshState();writeState(fresh);writeProfile(plan,fresh.settings,today);
assert.deepEqual(readState().records,[]);
assert.deepEqual(readState().plan[6].items,plan[6].items);
console.log('PASS: saved plan replaces pending work; preserves completed exercise snapshots and past dates; reload, rest-to-work, new work after finish, partial completion, first use');
